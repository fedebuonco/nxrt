#!/usr/bin/env python3
"""Onboard a Switch title into nxrt: check a port's inputs, or scaffold a new port.

    python3 tools/onboard.py check --port /path/to/port
    python3 tools/onboard.py scaffold --game-dir /path/to/extracted --id mygame --name "My Game" --out /path/to/port

`scaffold` writes only the shared port skeleton (Makefile, nx_game metadata, README); generation is the normal
`make gen` step. `check` is read-only and reports exactly which onboarding inputs are missing.
"""
import argparse, json, os, re, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from nso import Nso  # noqa: E402
from survey import summarize, load_hle  # noqa: E402


def parse_makefile(port):
    info = {"id": None, "exe": None, "modules": [], "src": []}
    path = os.path.join(port, "Makefile")
    if not os.path.exists(path):
        return info
    with open(path, encoding="utf-8", errors="replace") as f:
        lines = f.readlines()
    for line in lines:
        m = re.match(r"\s*GAME_ID\s*:?=\s*(\S+)", line)
        if m: info["id"] = m.group(1)
        m = re.match(r"\s*GAME_EXE\s*:?=\s*(\S+)", line)
        if m: info["exe"] = m.group(1)
        m = re.match(r"\s*GAME_MODULES\s*:?=\s*(.*)", line)
        if m:
            for item in m.group(1).split():
                if ":" in item:
                    name, base = item.split(":", 1)
                    info["modules"].append((name, int(base, 0)))
        m = re.match(r"\s*GAME_SRC\s*:?=\s*(.*)", line)
        if m: info["src"] = m.group(1).split()
    return info


def check(port):
    mk = parse_makefile(port)
    exefs = os.path.join(port, "data", "extracted", "exefs")
    rows = []
    def add(name, ok, detail="", required=True):
        rows.append({"check": name, "ok": bool(ok), "required": required, "detail": detail})
    add("Makefile", os.path.exists(os.path.join(port, "Makefile")), mk["id"] or "")
    add("exefs/main", os.path.exists(os.path.join(exefs, "main")))
    add("exefs/main.npdm", os.path.exists(os.path.join(exefs, "main.npdm")))
    add("exefs/sdk", os.path.exists(os.path.join(exefs, "sdk")))
    add("generated", bool([p for p in os.listdir(os.path.join(port, "generated"))] if os.path.isdir(os.path.join(port, "generated")) else []))
    build = os.path.join(port, "build")
    add("executable", os.path.exists(os.path.join(build, (mk["exe"] or "recomp"))))
    add("game dylib", any(f.startswith(mk["id"] or "") and f.endswith(".dylib") for f in os.listdir(build)) if os.path.isdir(build) else False)
    s = None
    if os.path.exists(os.path.join(exefs, "main")):
        try:
            n = Nso(os.path.join(exefs, "main"))
            hle = load_hle(os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "runtime", "hle", "hle_symbols.txt"))
            s = summarize(n, hle)
            resolved = set()
            for name, _ in mk["modules"]:
                if name != "main" and os.path.exists(os.path.join(exefs, name)):
                    resolved |= {x[0] for x in Nso(os.path.join(exefs, name)).exports()}
            imports = {x[0] for x in n.imports()}
            unresolved = sorted(imports - resolved)
            s["resolved_by_modules"] = len(imports & resolved)
            s["unresolved"] = unresolved
            s["unresolved_hle"] = sorted(set(unresolved) & hle)
            s["unresolved_missing"] = sorted(set(unresolved) - hle)
            add("module imports", not s["unresolved_missing"],
                f"{len(imports)} imports, {len(imports & resolved)} resolved by modules, "
                f"{len(s['unresolved'])} unresolved ({len(s['unresolved_missing'])} without HLE)", required=False)
            add("HLE coverage", not s["unresolved_missing"], f"{len(s['unresolved_hle'])} unresolved HLE, {len(s['unresolved_missing'])} missing", required=False)
        except Exception as e:
            add("NSO survey", False, str(e))
    return {"port": os.path.abspath(port), "makefile": mk, "checks": rows, "survey": s}


def scaffold(game_dir, game_id, name, out, title_id=0):
    exefs = game_dir if os.path.basename(game_dir) == "exefs" else os.path.join(game_dir, "exefs")
    main = os.path.join(exefs, "main")
    if not os.path.exists(main):
        raise SystemExit(f"no NSO at {main}")
    n = Nso(main)
    build = [int(x, 16) for x in re.findall(r"..", n.build_id)]
    modules = [("main", 0x7000000000)]
    if os.path.exists(os.path.join(exefs, "sdk")):
        modules.append(("sdk", 0x7006000000))
    os.makedirs(out, exist_ok=True)
    mods = " ".join(f"{m}:0x{b:x}" for m, b in modules)
    mk = f'''# {name} on nxrt: generated by tools/onboard.py. NXRT=<checkout> builds against another tree.
NXRT     ?= /Applications/nxrt.app/Contents/Resources/nxrt
GAME_ID  := {game_id}
GAME_EXE := {game_id}recomp
GAME_MODULES := {mods}
GAME_SRC := $(wildcard runtime/*.c) $(wildcard runtime/hle/*.c) $(wildcard runtime/ui/*.mm)
include $(NXRT)/nxrt.mk
'''
    open(os.path.join(out, "Makefile"), "w").write(mk)
    os.makedirs(os.path.join(out, "runtime"), exist_ok=True)
    b8 = ", ".join(f"0x{x:02x}" for x in build[:8])
    modc = ", ".join(f'{{"{m}", 0x{b:x}ull}}' for m, b in modules)
    gc = f'''// {name} on nxrt: generated by tools/onboard.py; fill title_id from the NPDM if it is known.
#include "nxgame.h"

const NxGame nx_game = {{
    .info = {{
        .id = "{game_id}",
        .exe = "{game_id}recomp",
        .title = "{name}",
        .game_name = "{name}",
        .game_version = "1.0.0",
        .title_id = 0x{title_id:016X}ull,
        .build_id = {{{b8}}},  // exefs/main +0x40
        .bundle_id = "org.nxrt.{game_id}recomp",
        .data_dir = "{game_id}recomp",
        .ini = "{game_id}.ini",
        .version = "dev",
        .headline = "{name}",
        .romfs_probe = "",
        .modules = {{{modc}}},
    }},
}};
'''
    open(os.path.join(out, "runtime", f"{game_id}_game.c"), "w").write(gc)
    open(os.path.join(out, "README.md"), "w").write(f'''# {name}

Generated by `tools/onboard.py`. Put the game's extracted files under `data/extracted/` (`exefs/main`,
`exefs/main.npdm`, `exefs/sdk`, `romfs/`), then:

```
make gen B=build NXRT=/Users/fede/mastersw/build/nxrt-macos
make -j8 B=build NXRT=/Users/fede/mastersw/build/nxrt-macos
```

Next: `tools/onboard.py check --port .`, then `tools/smoke.py`/`tools/crash_report.py` after a run.
See docs/ONBOARDING.md.
''')
    return {"out": os.path.abspath(out), "build_id": n.build_id, "modules": modules}


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    c = sub.add_parser("check")
    c.add_argument("--port", default=".")
    c.add_argument("--json", action="store_true")
    r = sub.add_parser("run")
    r.add_argument("--port", default=".")
    r.add_argument("--nxrt", default=os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
    r.add_argument("--frames", type=int, default=300)
    r.add_argument("--no-build", action="store_true")
    s = sub.add_parser("scaffold")
    s.add_argument("--game-dir", required=True)
    s.add_argument("--id", required=True)
    s.add_argument("--name", default=None)
    s.add_argument("--title-id", default="0")
    s.add_argument("--out", required=True)
    a = ap.parse_args(argv)
    if a.cmd == "check":
        r = check(a.port)
        good = all(x["ok"] for x in r["checks"] if x["required"])
        if a.json:
            print(json.dumps(r, indent=2, sort_keys=True)); return 0 if good else 1
        print(f"port {r['port']}")
        for x in r["checks"]:
            tag = "ok   " if x["ok"] else ("WARN " if not x["required"] else "MISS ")
            print(tag + x["check"] + (f"  ({x['detail']})" if x["detail"] else ""))
        if r["survey"]:
            print(f"imports {r['survey']['imports']}, resolved by modules {r['survey'].get('resolved_by_modules', 0)}, "
                  f"unresolved {len(r['survey'].get('unresolved', []))}")
        return 0 if good else 1
    if a.cmd == "run":
        import subprocess, time
        port = os.path.abspath(a.port); mk = parse_makefile(port)
        exe = os.path.join(port, "build", (mk["exe"] or "recomp"))
        if not a.no_build:
            p = subprocess.run(["make", "-j8", "B=build", f"NXRT={a.nxrt}"], cwd=port)
            if p.returncode: return p.returncode
        env = dict(os.environ, NXRT_DATA_ROOT=os.path.join(port, "data"), NXRT_NO_LAUNCHER="1",
                   NXRT_WINDOW_SHOT=str(a.frames), NXRT_SHOT_PATH=os.path.join(port, "build", "onboard.png"),
                   NXRT_EXIT_AFTER_SHOT="1", NXRT_METAL4="1")
        log = os.path.join(port, "build", "onboard.log")
        with open(log, "wb") as f:
            p = subprocess.run([exe], cwd=port, env=env, stdout=f, stderr=subprocess.STDOUT)
        print(f"exit {p.returncode}; log {log}")
        if p.returncode:
            os.system(f"python3 {os.path.join(os.path.dirname(os.path.abspath(__file__)), 'crash_report.py')} --port {port} --log {log}")
        return 1 if p.returncode else 0
    r = scaffold(os.path.abspath(a.game_dir), a.id, a.name or a.id, os.path.abspath(a.out), int(a.title_id, 0))
    print(f"scaffolded {r['out']} (build id {r['build_id']}, modules {r['modules']})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
